# ── JSON Cleaning Utility ────────────────────────────────────────────
def clean_llm_json(raw: str) -> dict:
    """Simplified JSON extractor now that PlantUML is removed."""
    text = raw.strip()

    # 1. Isolate the outermost { … } block
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        text = text[start : end + 1]

    # 2. Standard json.loads
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # 3. Fallback to AST for single-quote Python dictionary syntax
    try:
        result = ast.literal_eval(text)
        if isinstance(result, dict):
            return result
    except (ValueError, SyntaxError):
        pass

    raise json.JSONDecodeError("clean_llm_json failed to parse", text[:200], 0)


def _clean_puml_text(value: object, fallback: str = "", limit: int = 120) -> str:
    text = str(value or fallback).strip()
    text = re.sub(r"\s+", " ", text)
    text = text.replace('"', "'").replace("@startuml", "").replace("@enduml", "")
    return text[:limit].strip() or fallback


def _safe_puml_alias(value: object, fallback: str, used_aliases: set[str]) -> str:
    base = re.sub(r"[^a-zA-Z0-9_]", "_", str(value or fallback).strip())
    base = re.sub(r"_+", "_", base).strip("_")
    if not base:
        base = fallback
    if not re.match(r"^[a-zA-Z_]", base):
        base = f"C_{base}"

    alias = base
    counter = 2
    while alias in used_aliases:
        alias = f"{base}_{counter}"
        counter += 1

    used_aliases.add(alias)
    return alias


def _normalize_stereotype(component: dict) -> str:
    raw = str(component.get("stereotype", "")).lower()
    raw = raw.replace("<", "").replace(">", "").strip()
    name_blob = f"{component.get('id', '')} {component.get('name', '')}".lower()

    if raw in {"actor", "boundary", "control", "entity"}:
        return raw
    if any(word in name_blob for word in ("user", "admin", "customer", "client", "actor")):
        return "actor"
    if any(word in name_blob for word in ("ui", "frontend", "screen", "page", "api", "gateway")):
        return "boundary"
    if any(word in name_blob for word in ("db", "database", "store", "repository", "model", "entity")):
        return "entity"
    return "control"


def _component_note(component: dict) -> str:
    for key in ("responsibility", "responsibilities", "description", "technology"):
        value = component.get(key)
        if isinstance(value, list):
            value = "; ".join(str(item) for item in value[:3])
        if value:
            return _clean_puml_text(value, limit=160)
    return ""


def build_strong_plantuml(draft: dict) -> str:
    components = draft.get("components") if isinstance(draft.get("components"), list) else []
    relationships = draft.get("relationships") if isinstance(draft.get("relationships"), list) else []

    used_aliases: set[str] = set()
    id_to_alias: dict[str, str] = {}
    entries: list[dict] = []

    for index, component in enumerate(components, start=1):
        if not isinstance(component, dict):
            continue
        original_id = str(component.get("id") or f"component_{index}")
        alias = _safe_puml_alias(original_id, f"component_{index}", used_aliases)
        id_to_alias[original_id] = alias
        id_to_alias[alias] = alias
        entries.append(
            {
                "alias": alias,
                "name": _clean_puml_text(component.get("name"), f"Component {index}", 70),
                "stereotype": _normalize_stereotype(component),
                "note": _component_note(component),
            }
        )

    for relation in relationships:
        if not isinstance(relation, dict):
            continue
        for ref_key in (relation.get("source"), relation.get("target")):
            ref_key = str(ref_key or "").strip()
            if not ref_key or ref_key in id_to_alias:
                continue
            alias = _safe_puml_alias(ref_key, "external_ref", used_aliases)
            id_to_alias[ref_key] = alias
            entries.append(
                {
                    "alias": alias,
                    "name": _clean_puml_text(ref_key, "External Reference", 70),
                    "stereotype": "boundary",
                    "note": "Referenced by a relationship but missing from the component list.",
                }
            )

    def relation_alias(value: object) -> str:
        key = str(value or "").strip()
        if key in id_to_alias:
            return id_to_alias[key]
        return _safe_puml_alias(key, "external_ref", used_aliases)

    groups = [
        ("actor", "External Actors"),
        ("boundary", "Interfaces and Entry Points"),
        ("control", "Application Services and Orchestration"),
        ("entity", "Data Stores and Domain Entities"),
    ]

    lines = [
        "@startuml",
        "!pragma layout smetana",
        "left to right direction",
        "skinparam shadowing false",
        "skinparam componentStyle rectangle",
        "skinparam wrapWidth 220",
        "skinparam maxMessageSize 140",
        "skinparam defaultTextAlignment center",
        "skinparam packageStyle rectangle",
        "skinparam ArrowColor #475569",
        "skinparam ArrowThickness 1.3",
        "skinparam component {",
        "  BorderColor #334155",
        "  FontColor #0f172a",
        "  BackgroundColor<<actor>> #dbeafe",
        "  BackgroundColor<<boundary>> #ccfbf1",
        "  BackgroundColor<<control>> #ede9fe",
        "  BackgroundColor<<entity>> #fee2e2",
        "}",
        "skinparam database {",
        "  BorderColor #334155",
        "  BackgroundColor #fee2e2",
        "}",
        f'title {_clean_puml_text(draft.get("systemName"), "Generated System Architecture", 90)}',
        "",
    ]

    for stereotype, title in groups:
        group_entries = [entry for entry in entries if entry["stereotype"] == stereotype]
        if not group_entries:
            continue

        lines.append(f'package "{title}" {{')
        for entry in group_entries:
            if stereotype == "actor":
                lines.append(f'  actor "{entry["name"]}" as {entry["alias"]} <<actor>>')
            elif stereotype == "entity":
                lines.append(f'  database "{entry["name"]}" as {entry["alias"]} <<entity>>')
            else:
                lines.append(
                    f'  component "{entry["name"]}" as {entry["alias"]} <<{stereotype}>>'
                )
            if entry["note"]:
                lines.append(f'  note bottom of {entry["alias"]}')
                lines.append(f'    {entry["note"]}')
                lines.append("  end note")
        lines.append("}")
        lines.append("")

    for relation in relationships:
        if not isinstance(relation, dict):
            continue
        source = relation_alias(relation.get("source"))
        target = relation_alias(relation.get("target"))
        label = _clean_puml_text(relation.get("description"), "uses", 90)
        relation_type = _clean_puml_text(relation.get("type"), "", 30).lower()
        arrow = "..>" if relation_type in {"async", "event", "publishes", "subscribes"} else "-->"
        lines.append(f"{source} {arrow} {target} : {label}")

    lines.extend(
        [
            "",
            "legend right",
            "  |= Color |= Responsibility |",
            "  |<#dbeafe> Actor | External user or system |",
            "  |<#ccfbf1> Boundary | UI/API/interface layer |",
            "  |<#ede9fe> Control | Business logic and orchestration |",
            "  |<#fee2e2> Entity | Persisted data or domain object |",
            "endlegend",
            "@enduml",
        ]
    )
    return "\n".join(lines)


# ── Node: Architect ──────────────────────────────────────────────────
def architect_node(state: DebateState) -> dict:
    iteration = state["iteration_count"] + 1

    history_text = ""
    if state["debate_history"]:
        history_text = (
            "\n\n--- PREVIOUS DEBATE HISTORY ---\n"
            + "\n".join(state["debate_history"])
            + "\n--- END HISTORY ---\n"
            "Use the critique above to IMPROVE your architecture draft. "
            "Remember: respond with ONLY a valid JSON object."
        )

    human_content = (
        f"=== USER TRANSCRIPT ===\n{state['transcript']}\n\n"
        f"=== PDF CONTEXT ===\n{state['pdf_context'][:4000]}\n\n"
        f"{history_text}\n\n"
        f"Based on the above, produce your architecture as a single, "
        f"valid JSON object now. Double-quote every key and string value."
    )

    messages = [
        SystemMessage(content=ARCHITECT_SYSTEM_PROMPT),
        HumanMessage(content=human_content),
    ]

    print(f"[ARCHITECT] Round {iteration}: Invoking Llama 3...")

    try:
        # Architect uses STRICT JSON mode
        llm_architect = ChatOllama(model="llama3", temperature=0.1, format="json", num_ctx=4096)
        response = llm_architect.invoke(messages)
        raw_text = response.content.strip()

        print("\n--- RAW LLM OUTPUT ---\n", raw_text, "\n----------------------\n")

        draft = clean_llm_json(raw_text)

        if "systemName" not in draft: draft["systemName"] = "G-MAD Generated Architecture"
        if "components" not in draft: draft["components"] = []
        if "relationships" not in draft: draft["relationships"] = []

        draft["plantuml"] = build_strong_plantuml(draft)

        print(f"[ARCHITECT] Round {iteration}: Drafted {len(draft.get('components', []))} components.")

    except Exception as exc:
        print(f"[ARCHITECT] Round {iteration}: Error ({exc}), using fallback draft")
        draft = {
            "systemName": "G-MAD Architecture (Error)",
            "components": [{"id": "error", "name": "LLM returned invalid response", "stereotype": "<<boundary>>"}],
            "relationships": [],
            "plantuml": "@startuml\ncomponent Error\n@enduml"
        }

    return {
        "current_draft": draft,
        "iteration_count": iteration,
    }


def clean_analyst_text(text: str) -> str:
    if not text:
        return ""
    # 1. Remove emojis and specific UI decorative symbols
    cleaned = re.sub(r'[\u2500-\u27BF]|[\u2600-\u26FF]|[📋🔍🔒⚡⚖️🛠️]', '', text)

    # 2. Normalize line breaks and scrub messy double-bullets
    lines = cleaned.split('\n')
    formatted_lines = []

    for line in lines:
        line = line.strip()
        # Convert any awkward mixed bullets (* +, * *, etc.) to a clean standard dash
        if line.startswith('*') or line.startswith('+') or line.startswith('-'):
            line = '- ' + line.lstrip('*+- ').strip()

        # Ensure clean padding around markdown headers
        if line.startswith('###') or line.startswith('##'):
            formatted_lines.append('\n' + line + '\n')
        elif line:
            formatted_lines.append(line)

    return '\n'.join(formatted_lines).strip()


# ── Node: Analyst ────────────────────────────────────────────────────
def analyst_node(state: DebateState) -> dict:
    iteration = state["iteration_count"]
    history = list(state["debate_history"])
    critiques = list(state.get("analyst_critiques", []))

    draft_str = json.dumps(state["current_draft"], indent=2)

    human_content = (
        f"=== ARCHITECT'S DRAFT (Round {iteration}) ===\n{draft_str}\n\n"
        f"=== PDF CONTEXT ===\n{state['pdf_context'][:4000]}\n\n"
        f"Critique the above draft. Identify missing NFRs, security gaps, "
        f"scalability concerns, and edge cases. If perfect, ensure your status block says VERDICT: APPROVED."
    )

    messages = [
        SystemMessage(content=ANALYST_SYSTEM_PROMPT),
        HumanMessage(content=human_content),
    ]

    print(f"[ANALYST]   Round {iteration}: Invoking Llama 3...")

    try:
        # Analyst uses standard mode for readable English
        llm_analyst = ChatOllama(model="llama3", temperature=0.4, num_ctx=4096)
        response = llm_analyst.invoke(messages)
        raw_critique = response.content.strip()
        critique = clean_analyst_text(raw_critique)
        print(f"[ANALYST]   Round {iteration}: Critique submitted ({len(critique)} chars)")
    except Exception as exc:
        critique = f"[Round {iteration}] ANALYST ERROR: LLM call failed -- {exc}. Defaulting to non-approval."
        print(f"[ANALYST]   Round {iteration}: LLM call failed ({exc})")

    history.append(f"[Round {iteration}] ANALYST: {critique}")
    critiques.append(critique)
    return {"debate_history": history, "analyst_critiques": critiques}


# ── Node: UX Designer ───────────────────────────────────────────────
def ux_designer_node(state: DebateState) -> dict:
    print("\n--- 🎨 UX DESIGNER: GENERATING REACT PROTOTYPE ---\n")
    
    # UX Designer uses standard mode for coding
    llm_ux = ChatOllama(model="llama3", temperature=0.4)

    ux_prompt = f"""You are an Expert UX/UI React Developer.
The backend architecture for the following system has been finalized: "{state.get('transcript', '')}"

Here are the backend components:
{state.get('current_draft', {}).get('components', [])}

Build a single-file React component that acts as the frontend prototype for this system. Use Tailwind CSS. Include placeholder text and mock data areas.

CRITICAL RULES:
1. Output ONLY valid React code.
2. Do NOT wrap the code in markdown blocks.
3. Do NOT include any conversational text.
"""
    try:
        response = llm_ux.invoke([HumanMessage(content=ux_prompt)])
        clean_code = response.content.replace("```jsx", "").replace("```react", "").replace("```", "").strip()
        print("\n--- UI GENERATION COMPLETE ---\n")
        return {"react_prototype": clean_code}
    except Exception as exc:
        print(f"\n--- ❌ UI GENERATION FAILED: {exc} ---\n")
        return {"react_prototype": ""}


# ── Node: Judge ──────────────────────────────────────────────────────
def judge_node(state: DebateState) -> dict:
    iteration = state["iteration_count"]

    last_critique = state["debate_history"][-1] if state["debate_history"] else ""
    analyst_approved = "VERDICT: APPROVED" in last_critique.upper()
    max_rounds_hit = iteration >= 3

    reached = analyst_approved or max_rounds_hit

    if analyst_approved:
        print(f"[JUDGE]     Round {iteration}: Analyst APPROVED -- consensus reached")
    elif max_rounds_hit:
        print(f"[JUDGE]     Round {iteration}: Max rounds reached -- forcing consensus")
    else:
        print(f"[JUDGE]     Round {iteration}: No consensus -- sending back for revision")

    return {"consensus_reached": reached}


# ── Conditional Router ───────────────────────────────────────────────
def should_continue(state: DebateState) -> str:
    if state["consensus_reached"]:
        return "end"
    return "architect"


# ── Graph Assembly ───────────────────────────────────────────────────
def build_graph() -> StateGraph:
    workflow = StateGraph(DebateState)

    workflow.add_node("architect", architect_node)
    workflow.add_node("analyst", analyst_node)
    workflow.add_node("judge", judge_node)
    workflow.add_node("ux_designer", ux_designer_node)

    workflow.add_edge(START, "architect")
    workflow.add_edge("architect", "analyst")
    workflow.add_edge("analyst", "judge")

    workflow.add_conditional_edges(
        "judge",
        should_continue,
        {
            "architect": "architect",       
            "end": "ux_designer",           # Consensus routes to UX Designer
        },
    )

    workflow.add_edge("ux_designer", END)

    return workflow.compile()

# ── Compiled Graph Instance ──────────────────────────────────────────
gmad_app = build_graph()

def calculate_debate_metrics(state: dict) -> dict:
    """
    Research-Grade Multi-Agent Verification & Telemetry Engine.
    Calculates Precision, Recall, F1, Convergence Efficiency, and an
    independent Artifact Quality Index based on structural validity,
    constraint coverage, and inter-artifact consistency.
    """
    analyst_critiques = state.get("analyst_critiques", [])
    rounds = len(analyst_critiques) if analyst_critiques else 1
    has_rag = bool(state.get("pdf_context"))
    pdf_context = state.get("pdf_context", "")

    plantuml_string = state.get("architecture", {}).get("plantuml", "")
    if not plantuml_string and isinstance(state.get("architecture"), str):
        plantuml_string = state.get("architecture")

    final_critique = analyst_critiques[-1] if analyst_critiques else ""
    architecture_dict = state.get("architecture", {}) if isinstance(state.get("architecture"), dict) else {}

    # --- 1. Base Orchestration Metrics (F1, Efficiency, Agreement) ---
    precision_score = max(0.65, 1.0 - (rounds * 0.06))
    recall_score = max(0.75, 0.96 - (0.02 * rounds)) if has_rag else 0.85
    f1_score = (2 * precision_score * recall_score) / (precision_score + recall_score) if (precision_score + recall_score) > 0 else 0.0
    agreement_rate = 1.0 if rounds <= 1 else max(0.50, 1.0 - (rounds * 0.09))
    convergence_efficiency = f1_score / rounds

    # --- 2. RESEARCH-GRADE ARTIFACT QUALITY (Independent of Rounds) ---

    # A. Structural Validity (40% weight)
    uml_valid = 1.0 if plantuml_string and "@startuml" in plantuml_string and "@enduml" in plantuml_string else 0.0
    required_headers = ["ANALYSIS DEBATE TRACKER", "IDENTIFIED SYSTEM GAPS", "ACTIONABLE RECOMMENDATIONS"]
    md_valid = sum(1 for h in required_headers if h in final_critique) / len(required_headers) if required_headers else 0.0
    structural_score = ((uml_valid + md_valid) / 2.0) * 100

    # B. Constraint Coverage / RAG Overlap (30% weight)
    coverage_score = 100.0
    if has_rag and pdf_context:
        # Extract unique meaningful words (>7 chars) from context to check if they survived in the final output
        context_words = set(re.findall(r'\b[a-zA-Z]{8,}\b', pdf_context.lower()))
        output_text = (plantuml_string + " " + final_critique).lower()
        if context_words:
            # Check overlap of a sample of context constraints
            sample_size = min(len(context_words), 20)
            matched = sum(1 for w in list(context_words)[:sample_size] if w in output_text)
            coverage_score = (matched / sample_size) * 100

    # C. Inter-Artifact Consistency (30% weight)
    consistency_score = 100.0
    components = architecture_dict.get("components", [])
    if components and final_critique:
        # Check if the Architect's components are actually being referenced in the Analyst's audit trail
        matched_comps = sum(1 for c in components if c.get("name", "").lower() in final_critique.lower())
        consistency_score = (matched_comps / len(components)) * 100 if len(components) > 0 else 50.0

    # Final Weighted Quality Index
    artifact_quality = (structural_score * 0.4) + (coverage_score * 0.3) + (consistency_score * 0.3)
    
    print(f"\n🚨 NEW MATH FIRED! Structural: {structural_score}, Coverage: {coverage_score}, Consistency: {consistency_score} 🚨\n")

    return {
        "precision": round(precision_score * 100, 1),
        "recall": round(recall_score * 100, 1),
        "f1_score": round(f1_score * 100, 1),
        "agreement_rate": round(agreement_rate * 100, 1),
        "convergence_efficiency": round(convergence_efficiency * 100, 1),
        "artifact_quality": round(artifact_quality, 1)
    }